{
  SDL_Window* window = nullptr;
  SDL_Renderer* renderer = nullptr;
  SDL_Texture* texture = nullptr;
  SDL_AudioStream* audioStream = nullptr;
  bool imguiInitialized = false;
  std::optional<gbemu::GameBoy> gameBoy;
  bool running = true;
  bool paused = false;
  bool audioEnabled = false;
  float audioVolume = 1.0F;
  int videoScale = DEFAULT_VIDEO_SCALE;
  bool fullscreen = false;
  std::optional<std::string> currentRomPath;
  std::optional<std::string> error;
  Uint64 errorShownAtTicks = 0;
  std::optional<std::string> statusMessage;
  Uint64 statusMessageShownAtTicks = 0;
  std::mutex pendingRomPathMutex;
  std::optional<std::string> pendingRomPath;
#ifndef __EMSCRIPTEN__
  std::mutex pendingStatePathMutex;
  std::optional<std::string> pendingSaveStatePath;
  std::optional<std::string> pendingLoadStatePath;
#endif
  float menuBarHeight = 0.0F;
#ifdef __EMSCRIPTEN__
  Uint64 emulationStartTicks = 0;
  std::uint64_t framesEmulated = 0;
#endif
};

void
App::resetGame(Impl& impl)
{
  // NOLINTNEXTLINE(bugprone-unchecked-optional-access)
  impl.gameBoy->reset();
  impl.error.reset();
}

void
App::setMode(Impl& impl, gbemu::Mode mode)
{
  // NOLINTNEXTLINE(bugprone-unchecked-optional-access) - see resetGame().
  if (const auto result = impl.gameBoy->setMode(mode); !result) {
    std::cerr << "Warning: failed to set mode: " << result.error() << '\n';
  }
}

void
App::syncAudioDeviceState(Impl& impl)
{
  if (impl.audioStream == nullptr) {
    return;
  }
  if (impl.audioEnabled && !impl.paused) {
    SDL_ResumeAudioStreamDevice(impl.audioStream);
  } else {
    SDL_PauseAudioStreamDevice(impl.audioStream);
  }
}

void
App::togglePause(Impl& impl)
{
  impl.paused = !impl.paused;
  syncAudioDeviceState(impl);
}

void
App::toggleAudioEnabled(Impl& impl)
{
  impl.audioEnabled = !impl.audioEnabled;
  syncAudioDeviceState(impl);
}

void
App::applyWindowSize(Impl& impl)
{
  SDL_SetWindowSize(impl.window,
                    windowWidthFor(impl.videoScale),
                    windowHeightFor(impl.videoScale) +
                      static_cast<int>(std::ceil(impl.menuBarHeight)));
}

void
App::setVideoScale(Impl& impl, int scale)
{
  impl.videoScale = scale;
  if (impl.fullscreen) {
    SDL_SetWindowFullscreen(impl.window, false);
    impl.fullscreen = false;
  }
  applyWindowSize(impl);
}

